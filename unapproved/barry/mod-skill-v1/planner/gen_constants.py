"""mod_skill planner: generate the TS constant tables for the Page (constants.ts / constants.json).
Run from this folder:  python3 gen_constants.py
Win tables: same aggregation as planner-v1/gen_constants.py (district mean over the 5 live tracks + hardest track on the
union of r knots, off-tune POW-share delta grids, x100 ints). mod_skill numbers come from ../ (mod_skill.py, the
recommended calibration calib_mk1_list_spill_tougephee.json)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..")); sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "sim"))
from velocity_shift import equations as E, progression as P
import mod_skill as M

T = P._table(); O = P._off(); DISTS = ("street", "wangan", "touge")
cal = json.load(open(os.path.join(HERE, "..", "calib_mk1_list_spill_tougephee.json")))
KN = {}; WC = {}
for pr in P.PROFILES:
    WC[pr] = {}
    for turns in (10, 20, 30):
        WC[pr][turns] = {}
        for d in DISTS:
            names = P.tracks(d)
            knots = sorted({x[0] for p_ in P.PROFILES for n in T["q"][p_][str(turns)] for x in T["q"][p_][str(turns)][n]})
            KN.setdefault(turns, knots); assert KN[turns] == knots
            p0 = E.DISTRICT_TUNE[d][0]; rs, ps = O["_rs"], O["_ps"]
            q = lambda a: [int(round(x * 100)) for x in a]
            dgrid = lambda ns: [round(sum(P._off_win(pr, r, turns, n, p) - P._off_win(pr, r, turns, n, p0) for n in ns) / len(ns), 4) for r in rs for p in ps]
            e = dict(m=q([sum(P._track_win(pr, r, turns, n) for n in names) / len(names) for r in knots]), dm=q(dgrid(names)))
            if turns in E.HARD_TRACK_TURNS[d]:
                h = E.BOSS_HARD_TRACK[d]
                e["h"] = q([P._track_win(pr, r, turns, h) for r in knots]); e["dh"] = q(dgrid([h]))
            WC[pr][turns][d] = e
C = dict(
    ROUNDS=list(DISTS), RUNGS=E.LADDER_RUNGS, KIND=E.LADDER_RUNG_KIND, TURNS=E.LADDER_TURNS, TARGET_R=E.LADDER_TARGET_R,
    C_ROUND=E.C_ROUND, CAP_POWER=list(M.CAP_POWER), CEIL=list(M.CEIL), STOCK_TOTAL=M.STOCK, BASE_MIN=750, BASE_MAX=1500,
    OWN_MIN=0.60, BAND=[E.BUILD_STAT_MIN_SHARE, E.BUILD_STAT_MAX_SHARE], TUNE=E.DISTRICT_TUNE,
    KITS={"street": ["P1", "P2", "H1", "E1"], "wangan": ["P1", "H1", "E1", "E2"], "touge": ["P1", "H1", "E1", "E2"]},
    STORY_XP=cal["story_table"], GRIND_XP=cal["grind_xp"], PRICE=[150.0, 700.0, 1200.0], WHOLESALE=E.WHOLESALE_DISCOUNT,
    PAY={"kid": E.BASE_PAYOUT_WILD, "mature": E.BASE_PAYOUT_CREW, "old_head": E.BASE_PAYOUT_CREW, "boss": E.BASE_PAYOUT_BOSS},
    PAY_MULT=E.ROUND_PAYOUT_MULT, GRIND_PAY_FRAC=E.GRIND_PAYOUT_FRACTION, DEBT=E.DEBT_AMOUNT, DEBT_SHARE=E.DEBT_SHARE,
    CATCHUP=dict(k=E.CATCHUP_XP_FRAC, share=list(E.CATCHUP_XP_SHARE)), HARD_TURNS={k: list(v) for k, v in E.HARD_TRACK_TURNS.items()},
    OFF_RS=O["_rs"], OFF_PS=O["_ps"], SKILL=[0.6, 0.8],
)
js = lambda x: json.dumps(x, separators=(",", ":"))
src = "// generated by unapproved/barry/mod-skill-v1/planner/gen_constants.py (do not edit)\n"
src += "export const C: any = " + js(C) + ";\nexport const KNOTS: any = " + js(KN) + ";\nexport const WIN: any = " + js(WC) + ";\n"
open(os.path.join(HERE, "constants.ts"), "w").write(src)
json.dump(C, open(os.path.join(HERE, "constants.json"), "w"), indent=1)
print("constants.ts", len(src), "bytes")
