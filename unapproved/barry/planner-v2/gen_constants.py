"""planner-v2: the Page's constant tables (constants.ts / constants.json), every value read from the LIVE sim code
(sim/velocity_shift/equations.py and mod_skill.py), plus the Monte Carlo win tables from build_tables.py (win_tables.json).
Run from this folder: python3 gen_constants.py"""
import json, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "sim"))
from velocity_shift import equations as E, mod_skill as M

W = json.load(open(os.path.join(HERE, "win_tables.json")))
assert W["heat_release"] == E.HEAT_RELEASE, "win tables were built at another HEAT_RELEASE: rerun build_tables.py"
D = list(M.DISTRICTS); R = list(M.RUNGS)
# highest Mk on sale at each rung: "pre" = before the race (wins = earlier rungs), "post" = after this rung's win
mk = lambda upto: M.unlocked_mk(0, {(0, x) for x in R[:upto]})
C = dict(
    COMMIT=W["commit"], HEAT_RELEASE=E.HEAT_RELEASE, ROUNDS=D, RUNGS=R, KIND=list(E.LADDER_RUNG_KIND), TURNS=list(E.LADDER_TURNS),
    STOCK=E.MS_STOCK_POINTS, SLOTS=E.MOD_SLOTS, TIER=[list(t) for t in E.MS_TIER_POINTS], CAP=list(E.MS_ROUND_CAP_POINTS),
    PRICE=[[M.mod_price(g, k) for k in (1, 2, 3)] for g in range(3)],
    PRICE_WS=[[M.mod_price(g, k, wholesale=True) for k in (1, 2, 3)] for g in range(3)],
    WHOLESALE_ON=[E.wholesale_active(r) for r in range(3)], WHOLESALE=E.WHOLESALE_DISCOUNT,
    MK_PRE=[mk(j) for j in range(7)], MK_POST=[mk(j + 1) for j in range(7)],
    STORY_XP=[list(x) for x in E.MS_STORY_XP], WILD_XP=list(E.MS_WILD_XP), REQ_WILDS=list(E.MS_REQUIRED_WILDS), NM_CAP=E.MS_NM_XP_CAP,
    FLOOR={d: list(E.MS_FLOOR_POINTS[d]) for d in D}, CREW={d: list(E.MS_CREW_BUDGET[d]) for d in D},
    PURSE=[{k: E.purse(r, k) for k in ("kid", "mature", "old_head", "boss")} for r in range(3)],
    WILD_PURSE=[E.purse(r, "kid", grind=True) for r in range(3)], DEBT=E.DEBT_AMOUNT, DEBT_SHARE=E.DEBT_SHARE,
    TUNE={d: list(E.DISTRICT_TUNE[d]) for d in D}, TRACK=W["track"], SKILL=[W["q"][0], W["q"][-1]], N_MC=W["n"], SEED=W["seed"],
)
WT = dict(Q=W["q"], PTS=W["pts"], WIN=W["win"])
js = lambda x: json.dumps(x, separators=(",", ":"))
src = "// generated by unapproved/barry/planner-v2/gen_constants.py (do not edit)\n"
src += "export const C: any = " + js(C) + ";\nexport const WT: any = " + js(WT) + ";\n"
open(os.path.join(HERE, "constants.ts"), "w").write(src)
json.dump(dict(C=C, WT=WT), open(os.path.join(HERE, "constants.json"), "w"), indent=1)
print("constants.ts", len(src), "bytes; commit", C["COMMIT"], "HEAT_RELEASE", C["HEAT_RELEASE"], "MK_PRE", C["MK_PRE"], "MK_POST", C["MK_POST"])
