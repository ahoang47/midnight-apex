"""Export the econ-v1 G2 win-rate tables (numpy npz) to a stdlib JSON oracle for the live sim.

Writes sim/config/winrate_g2_econ_v1.json, read by sim/velocity_shift/progression.py (CI has no numpy).
Values are the same means wr.py uses (over seeds x boss styles), per profile x r x track x length, in %.
Duplicate r across sweep files keep the first occurrence, as wr.py's argmin does.
Run from this folder: python export_live_table.py
"""
from __future__ import annotations
import json, os
import wr

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, "..", "..", "..", "sim", "config", "winrate_g2_econ_v1.json"))


def main():
    wr._init()
    tracks = [list(t) for t in wr._TRACKS]
    src = {"c6060": (wr._OLD_MEAN, wr._OLD_R, 0), "c8080": (wr._OLD_MEAN, wr._OLD_R, 1),
           "c6080": (wr._MIX_MEAN, wr._MIX_R, 0), "c8060": (wr._MIX_MEAN, wr._MIX_R, 1)}
    prof = {}
    for pr, (mean, R, meas) in src.items():
        seen = {}
        for i, r in enumerate(R.tolist()):
            if r not in seen:
                seen[r] = i
        rs = sorted(seen)
        win = {}
        for k, T in enumerate((10, 20, 30)):
            win[str(T)] = [[round(100 * float(mean[meas, seen[r], ti, k, 0]), 4) for ti in range(len(tracks))] for r in rs]
        prof[pr] = {"r": rs, "win": win}
    out = {
        "_comment": ("G2 heat/load win rates (%) for the econ-v1 progression oracle. Source: unapproved/barry/round-ladder-v1 "
                     "results_r_sweep / results_picks / results_picks_grind (c6060, c8080) and unapproved/barry/econ-v1/results_mixed "
                     "(c6080, c8060); 9 seeds x 1000 races, 3 boss styles, mean over seeds and styles. Track set: the touge-lines-v1 "
                     "DRAFT laps (Street/Wangan 2 layouts x CW/CCW, Touge 1 layout uphill/downhill, Touge grade PLACEHOLDER), not "
                     "config/tracks_v1.json. District tunes street 0.50/0.25/0.25, wangan 0.25/0.30/0.45, touge 0.40/0.30/0.30 (POW/HAN/EN). "
                     "Generated by unapproved/barry/econ-v1/export_live_table.py."),
        "profiles": {"c6060": "read 0.6, average QTE, pacing 0.6", "c6080": "read 0.6, QTE 0.8, pacing 0.8",
                     "c8060": "read 0.8, average QTE, pacing 0.6", "c8080": "read 0.8, QTE 0.8, pacing 0.8"},
        "tracks": tracks,
        "lengths": [10, 20, 30],
        "q": prof,
    }
    with open(OUT, "w") as fh:
        json.dump(out, fh, separators=(",", ":"))
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
