"""planner-v1: generate the JS/TS constant tables for the campaign planner Page from the live Python sim.
Run from sim/:  python3 ../unapproved/barry/planner-v1/gen_constants.py   -> planner-v1/constants.ts (+ constants.json)
Win tables are pre-aggregated per (profile, race length, district): district mean over the 5 live tracks and the hardest
track, on the union of the r knots (exact for piecewise-linear interpolation), plus the off-tune delta grids
(POW share; mean of per-track deltas, exact except the per-track 0-100 clamp)."""
import json, os, sys
sys.path.insert(0, os.getcwd())
from velocity_shift import equations as E, progression as P
HERE = os.path.dirname(os.path.abspath(__file__))
T = P._table(); O = P._off()
DISTS = ("street", "wangan", "touge")
def r5(x): return round(float(x), 5)
win = {}
for pr in P.PROFILES:
    win[pr] = {}
    for turns in (10, 20, 30):
        win[pr][turns] = {}
        for d in DISTS:
            names = P.tracks(d); knots = sorted({x[0] for p_ in P.PROFILES for n in T["q"][p_][str(turns)] for x in T["q"][p_][str(turns)][n]})
            mean = [round(sum(P._track_win(pr, r, turns, n) for n in names) / len(names), 4) for r in knots]
            cell = dict(r=knots, m=mean)
            p0 = E.DISTRICT_TUNE[d][0]; rs, ps = O["_rs"], O["_ps"]
            def dgrid(ns):
                return [[round(sum(P._off_win(pr, r, turns, n, p) - P._off_win(pr, r, turns, n, p0) for n in ns) / len(ns), 4) for p in ps] for r in rs]
            cell["dm"] = dgrid(names)
            if turns in E.HARD_TRACK_TURNS[d]:
                h = E.BOSS_HARD_TRACK[d]
                cell["h"] = [round(P._track_win(pr, r, turns, h), 4) for r in knots]; cell["dh"] = dgrid([h])
            win[pr][turns][d] = cell
cat = [dict(id=k, g=v["group"], mk=v["mk"], st=v["stat"], pts=v["points"], price=v["price"], u=":".join(str(x) for x in v["unlock"])) for k, v in E.MOD_CATALOG.items()]
C = dict(
    SP_START=E.SP_START, SP_G=E.SP_GROWTH_PER_12_LEVELS, SP_SCALE=E.SP_POINT_SCALE, SP_CAP=E.SP_CAP_FRACTION, MOD_CAP=E.MOD_CAP_FRACTION,
    XP_BASE=E.XP_BASE, XP_G=E.XP_GROWTH, GRIND_FRAC=E.GRIND_FRAC, TAU=E.GRIND_TAPER_TAU, FLOOR=E.GRIND_TAPER_FLOOR,
    STORY_FILL=E.STORY_FILL, STORY_W=E.STORY_W, STORY_XP_MULT=E.STORY_XP_MULT, C_ROUND=E.C_ROUND, CAP=E.CAP_LEVEL, TARGET_R=E.LADDER_TARGET_R,
    RUNGS=E.LADDER_RUNGS, KIND=E.LADDER_RUNG_KIND, TURNS=E.LADDER_TURNS, ROUNDS=[d.lower() for d in E.ROUND_DISTRICTS],
    PAY={"kid": E.BASE_PAYOUT_WILD, "mature": E.BASE_PAYOUT_CREW, "old_head": E.BASE_PAYOUT_CREW, "boss": E.BASE_PAYOUT_BOSS},
    PAY_MULT=E.ROUND_PAYOUT_MULT, GRIND_PAY_FRAC=E.GRIND_PAYOUT_FRACTION, DEBT=E.DEBT_AMOUNT, DEBT_SHARE=E.DEBT_SHARE,
    WHOLESALE=E.WHOLESALE_DISCOUNT, AERO_MULT=E.AERO_PRICE_MULT, AERO_UNLOCK_AFTER=E.AERO_UNLOCK_AFTER, SLOTS=E.MOD_SLOTS, STOCK=E.MOD_STOCK_PART_POINTS,
    PATTERN=E.MOD_SLOT_PATTERN, TUNE=E.DISTRICT_TUNE, BAND=(E.BUILD_STAT_MIN_SHARE, E.BUILD_STAT_MAX_SHARE), RETUNE=E.RETUNE_BUDGET_FRACTION,
    HARD_TURNS={k: list(v) for k, v in E.HARD_TRACK_TURNS.items()}, CLEAR=E.CLEAR_THRESHOLD,
    FINALE=[dict(name=n, d=d.lower(), B=B, r=r) for (n, d, B), r, o in zip(E.FINALE, E.FINALE_TARGET_R, E.FINALE_OPPONENT)],
    FIN_CAP=E.FINALE_CAP_LEVEL, FIN_PURSE=E.FINALE_PURSE, ARC_GRIND_PAY=E.FINALE_GRIND_PURSE, ARC_GRIND_R=E.ARC_GRIND_R, ARC_FILL=E.ARC_STORY_FILL,
    ARC=[dict(id=a[0], d=a[2], T=a[3], r=a[4], share=a[5], purse=a[6], B=a[7]) for a in E.FINALE_ARC],
    STEP_DIST=["touge", "wangan", "street", "touge"], CATALOG=cat, WHOLESALE_TIERS=E.WHOLESALE_TIERS, AERO_MAX=E.AERO_MAX_EQUIPPED, GRIND_TURNS=E.GRIND_TURNS, OFF_RS=O["_rs"], OFF_PS=O["_ps"],
    CATCHUP=dict(k=E.CATCHUP_XP_FRAC, share=list(E.CATCHUP_XP_SHARE)),   # leftover XP carry-over, live since 2026-11-14 (R2 boss x1.5 is in STORY_XP_MULT)
)
# compact form for the Page: shared knots per race length, values x100 as ints, delta grids flattened (rs-major)
KN = {}; WC = {}
for pr in win:
    WC[pr] = {}
    for turns in win[pr]:
        WC[pr][turns] = {}
        for d, c in win[pr][turns].items():
            KN.setdefault(turns, c["r"]); assert KN[turns] == c["r"]
            q = lambda a: [int(round(x * 100)) for x in a]
            e = dict(m=q(c["m"]), dm=q([v for row in c["dm"] for v in row]))
            if "h" in c: e["h"] = q(c["h"]); e["dh"] = q([v for row in c["dh"] for v in row])
            WC[pr][turns][d] = e
json.dump(dict(C=C, WIN=win), open(os.path.join(HERE, "constants.json"), "w"), separators=(",", ":"))
def js(x): return json.dumps(x, separators=(",", ":"))
src = "// generated by unapproved/barry/planner-v1/gen_constants.py from sim/velocity_shift (do not edit)\n"
src += "export const C: any = " + js(C) + ";\n"
src += "export const KNOTS: any = " + js(KN) + ";\n"
src += "export const WIN: any = " + js(WC) + ";\n"
open(os.path.join(HERE, "constants.ts"), "w").write(src)
print("constants.ts", len(src), "bytes")
