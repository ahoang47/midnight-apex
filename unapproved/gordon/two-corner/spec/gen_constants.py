"""Generate the Godot constant file from the PINNED sim (sim/velocity_shift/equations.py).

Nothing is typed by hand: every value is read from the imported module at the pinned
commit and written out by name. Floats are also emitted as IEEE-754 bit patterns so
each engine can self-check that its parsed literal is bit-identical to Python's.
"""
import json, math, struct, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = ROOT / "_pin"
sys.path.insert(0, str(PIN / "sim"))
from velocity_shift import equations as E  # noqa: E402

commit = subprocess.check_output(["git", "-C", str(PIN), "rev-parse", "HEAD"], text=True).strip()

SCALARS = ["W0", "T_MAX", "L_MAX", "TAU_BETA", "TAU_P_TOP", "TAU_GAMMA", "MU", "ETA",
           "DECK_ALPHA", "HAND_SIZE", "LINE_ADHERENCE", "OPPONENT_QTE", "QTE_NORMALIZER",
           "PLAYER_QTE_MIN", "PLAYER_QTE_MAX", "PERFECT_QTE", "SABINE_BUDGET",
           # qte-v1 visible zone + per-phase QTE (pin f0efecf, Barry; Austin approved the re-pin 2026-11-11 10:56 PM PT)
           "QTE_ZONE_BASE_MS", "AVERAGE_PLAY_Q", "PHASE_QTE_UNPLAYED"]
STRUCTS = ["KNOT_WINDOW_105", "KAPPA_BY_LENGTH", "RACE_LENGTHS", "LINE_ALT_WEIGHTS", "LINE_SET_C", "LADDER_R", "LADDER_RUNGS",
           "QTE_ZONE_WIDTH_105", "QTE_SKILL_TARGET_E", "QTE_SKILL_SIGMA_OVER_A0", "QTE_PHASES"]

def bits(x):
    return struct.unpack("<q", struct.pack("<d", float(x)))[0]

# file:line of each constant's definition in the pinned sim (cited in the generated file)
import re
EQ = PIN / "sim" / "velocity_shift" / "equations.py"
_src = EQ.read_text().splitlines()
def line_of(n):
    for i, l in enumerate(_src, 1):
        if re.match(rf"^{n}\s*(:[^=]*)?=", l): return f"sim/velocity_shift/equations.py:{i}"
    raise KeyError(n)

data = {"_source": f"sim/velocity_shift/equations.py @ {commit}", "commit": commit, "values": {}, "float_bits": {}}
for n in SCALARS + STRUCTS:
    v = getattr(E, n)
    if isinstance(v, tuple):
        v = [list(t) if isinstance(t, tuple) else t for t in v]
    if isinstance(v, dict):
        v = {str(k): v[k] for k in v}
    data["values"][n] = v

def walk(prefix, v):
    if isinstance(v, float):
        data["float_bits"][prefix] = bits(v)
    elif isinstance(v, list):
        for i, x in enumerate(v): walk(f"{prefix}[{i}]", x)
    elif isinstance(v, dict):
        for k, x in v.items(): walk(f"{prefix}[{k}]", x)
for n, v in data["values"].items():
    walk(n, v)

(ROOT / "spec" / "constants.json").write_text(json.dumps(data, indent=1))

def flit(x):
    """Godot's decimal float parser is not correctly rounded (e.g. 0.9074726672615829 lands 1 ulp off), so long floats are
    written as an exact integer mantissa divided by powers of two (every step exact); headless_run.gd re-checks FLOAT_BITS."""
    r = repr(x)
    if len(r) <= 10 or x == 0.0 or not math.isfinite(x): return r
    m, e = math.frexp(x); mi = int(m * 2 ** 53); k = 53 - e
    assert mi * 2.0 ** -k == x
    out = str(mi)
    while k >= 32: out += " / 4294967296.0"; k -= 32
    if k > 0: out += f" / {float(2 ** k)!r}"
    elif k < 0: out += f" * {float(2 ** -k)!r}"
    return "(" + out + ")"

def lit(v):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, float): return flit(v)
    if isinstance(v, int): return str(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return "[" + ", ".join(lit(x) for x in v) + "]"
    if isinstance(v, dict): return "{" + ", ".join(f"{json.dumps(str(k))}: {lit(x)}" for k, x in v.items()) + "}"
    raise TypeError(v)

hdr = f"GENERATED by spec/gen_constants.py from sim/velocity_shift/equations.py @ {commit}. DO NOT EDIT. Values are the sim's, by name."
# KAPPA_BY_LENGTH keys must stay ints in engines
kap = {int(k): v for k, v in E.KAPPA_BY_LENGTH.items()}

data["source_lines"] = {n: line_of(n) for n in data["values"]}
(ROOT / "spec" / "constants.json").write_text(json.dumps(data, indent=1))
gd = [f"# {hdr}", "class_name SimConstants", "extends RefCounted", f'const PIN_COMMIT := "{commit}"']
for n, v in data["values"].items():
    gd.append(f"# {data['source_lines'][n]}")
    if n == "KAPPA_BY_LENGTH":
        gd.append(f"const {n} := " + "{" + ", ".join(f"{k}: {lit(x)}" for k, x in kap.items()) + "}")
    else:
        gd.append(f"const {n} := {lit(v)}")
gd.append("const FLOAT_BITS := {" + ", ".join(f'"{k}": {b}' for k, b in data["float_bits"].items()) + "}")
gd.append("const ALL := {" + ", ".join(f'"{n}": {n}' for n in data["values"]) + "}")
(ROOT / "godot" / "scripts").mkdir(parents=True, exist_ok=True)
(ROOT / "godot" / "scripts" / "sim_constants.gd").write_text("\n".join(gd) + "\n")

