#!/usr/bin/env python3
"""Generate scripts/globals.gd from sim/ (Barry's source of truth). Gordon [godot], touge-race.

Every value is read from the live sim by name and written with its sim/ file:line. Floats are emitted
as IEEE-754 bit patterns (decoded at load) because Godot's decimal parser is not correctly rounded.
Calibration values (heat.avg_heat_demand, heat.track_wear for the race lap) are COMPUTED by the sim
and written out, never re-derived in Godot. Run from anywhere:  python3 tools/touge_race/gen_globals.py
"""
import argparse, inspect, json, os, struct, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
# Local worktree sim/ may be behind origin; --sim / SIM_PATH can point at a live checkout
# (do not pull/rebase this worktree). --pin / SIM_PIN sets PIN_COMMIT (last sim/ commit).
_ap = argparse.ArgumentParser()
_ap.add_argument("--sim", default=os.environ.get("SIM_PATH", str(REPO / "sim")))
_ap.add_argument("--pin", default=os.environ.get("SIM_PIN"))
_ARGS, _ = _ap.parse_known_args()
_sim_arg = Path(_ARGS.sim).resolve()
SIM = _sim_arg if (_sim_arg / "velocity_shift").is_dir() else (_sim_arg / "sim")
sys.path.insert(0, str(SIM))
from velocity_shift import equations as E, heat as H, combat as CB  # noqa: E402

EQ_SRC = (SIM / "velocity_shift" / "equations.py").read_text().splitlines()
BLOCKS = "unapproved/barry/touge-race-parity/blocks.json"
CFG = json.loads((REPO / "spec" / "race_config.json").read_text())

def line_of(name):
    for i, l in enumerate(EQ_SRC, 1):
        if l.startswith(name + " ") or l.startswith(name + "="):
            return i
    raise KeyError(name)

def bits(x):
    return struct.unpack("<q", struct.pack("<d", float(x)))[0]

def gd(v):
    """GDScript literal; floats -> _f(bits) at runtime via F table (see below)."""
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, float): return "_d(%d)" % bits(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, (list, tuple)): return "[" + ", ".join(gd(x) for x in v) + "]"
    if isinstance(v, dict): return "{" + ", ".join("%s: %s" % (gd(k), gd(x)) for k, x in v.items()) + "}"
    raise TypeError(type(v))

def has_float(v):
    if isinstance(v, bool): return False
    if isinstance(v, float): return True
    if isinstance(v, (list, tuple)): return any(has_float(x) for x in v)
    if isinstance(v, dict): return any(has_float(x) for x in v.values())
    return False

NAMES = [
    # Phi/tau clash payoff
    "W0", "T_MAX", "L_MAX", "TAU_BETA", "TAU_P_TOP", "TAU_GAMMA", "STAT_M_W",
    "KAPPA_BY_LENGTH", "KAPPA_HEAT_MULT", "OPPONENT_QTE",
    "OPPONENT_QTE_SD", "OPPONENT_QTE_MIN", "OPPONENT_QTE_MAX", "OPPONENT_QTE_SEED_OFFSET",
    # lines
    "LINE_ADHERENCE", "LINE_ALT_WEIGHTS", "LINE_SET_C",
    # QTE (qte-v1)
    "QTE_ZONE_BASE_MS", "KNOT_WINDOW_105", "QTE_ZONE_WIDTH_105", "QTE_SKILL_TARGET_E", "QTE_SKILL_SIGMA_OVER_A0",
    "AVERAGE_PLAY_Q", "PHASE_QTE_UNPLAYED", "QTE_SCORE_DECIMALS", "QTE_PHASES",
    # G2 heat / load gauges
    "HEAT_ORDER", "CORNER_HEAT_COST", "CORNER_HEAT_PASSIVE", "HEAT_BASE_COST", "HEAT_REPEAT_SURCHARGE",
    "HEAT_CAP_TURNS", "HEAT_RECOVERY", "HEAT_SHARE_EXP", "HEAT_R_EXP", "HEAT_RELEASE", "OVERRUN_SLOPE",
    "OVERRUN_FLOOR", "LIMP_MULT", "HEAT_DEMAND_SLANT", "HEAT_REF_Q",
    "BOSS_HEAT_CAP_TURNS", "BOSS_HEAT_RECOVERY", "BOSS_HEAT_RELEASE", "BOSS_HEAT_LOCK_ON_PASSIVE",
    # ladder / parity cap
    "K_STEP", "LADDER_RUNGS", "LADDER_TARGET_R", "BOSS_TARGET_R", "BOSS_STAT_SHARES", "DISTRICTS",
    # crew ladder stats (mirrored; the touge race still runs on the car placeholder / draft blocks, not these)
    "MS_CREW_BUDGET",
    # Touge passing go-live (5c79dea): per-phase districts and the phase smoothing weight (equations.smooth_phase_qte)
    "PER_PHASE_DISTRICTS", "PHASE_SMOOTH_W",
]

def main():
    pin = _ARGS.pin or subprocess.check_output(["git", "-C", str(REPO), "log", "-1", "--format=%H", "--", "sim/"], text=True).strip()
    out = []
    w = out.append
    w("# GENERATED by tools/touge_race/gen_globals.py from sim/ @ %s. DO NOT EDIT BY HAND." % pin)
    w("# Values are the sim's, by name (sim/ is the source of truth, Barry). Floats are IEEE-754 bit patterns decoded at load.")
    w("# Touge-race only additions at the bottom are PLACEHOLDERS marked TODO(barry); they hold no numbers.")
    w("extends Node")
    w("const PIN_COMMIT := %s" % json.dumps(pin))
    w("static func _d(b: int) -> float:")
    w("\tvar a := PackedByteArray(); a.resize(8); a.encode_s64(0, b); return a.decode_double(0)")
    w("")
    for n in NAMES:
        v = getattr(E, n)
        src = "sim/velocity_shift/equations.py:%d" % line_of(n)
        w("# %s" % src)
        if has_float(v):
            w("static var %s = %s" % (n, gd(v)))
        else:
            w("const %s := %s" % (n, gd(v)))
    w("")
    # race lap = the sim's default touge track (match.race_setup falls back to the first official track of the district)
    district = CFG["district"]
    lap = CB.track_corners(district, int(CFG["track_index"]))
    tname = list(CB.official_tracks()[district])[int(CFG["track_index"])]
    assert lap == [c["corner"] for c in CFG["corners"]], "race_config corners must equal the sim track %s %s" % (tname, lap)
    w("# Race lap: sim/config/tracks_v1.json tracks.%s.%s (combat.track_corners(%r, %d))" % (district, tname, district, int(CFG["track_index"])))
    w("const RACE_DISTRICT := %s" % json.dumps(district))
    w("const RACE_TRACK := %s" % json.dumps(tname))
    w("const RACE_LAP := %s" % gd(lap))
    w("# COMPUTED by the sim: heat.avg_heat_demand() (sim/velocity_shift/heat.py:%d), HEAT_ORDER POW, HAN, EN" % (inspect.getsourcelines(H.avg_heat_demand)[1]))
    w("static var AVG_HEAT_DEMAND = %s" % gd(list(H.avg_heat_demand())))
    w("# COMPUTED by the sim: heat.track_wear(%r, RACE_LAP) (sim/velocity_shift/heat.py:%d)" % (district, inspect.getsourcelines(H.track_wear)[1]))
    w("static var TRACK_WEAR = %s" % gd(list(H.track_wear(district, lap))))
    w("# COMPUTED by the sim: combat.line_probs() (sim/velocity_shift/combat.py:%d)" % inspect.getsourcelines(CB.line_probs)[1])
    w("static var LINE_PROBS = %s" % gd(list(CB.line_probs())))
    w("")
    w("# ── Touge race car data (Austin 2026-11-19): all five cars in assets/cars are selectable; every car must sit inside the")
    w("# parity cap (K_STEP above: r between 1/K_STEP and K_STEP). Car choice is visual / model only. No mods, no retune.")
    w("# Rule from Austin via Barry: 3,000 points per car, each of POW / HAN / EN at 25-50 %. Barry's approved per-car blocks")
    w("# are pending, so each block is null and NO numbers are used here.")
    w("# TODO(barry): pending parity block")
    w("const CAR_STAT_BLOCKS := {\"brz\": null, \"gr_corolla\": null, \"mx5\": null, \"s2000\": null, \"wrx_sti\": null}")
    w("# TODO(barry): pending parity block. While a block is null the race uses an EVEN, EQUAL stand-in in normalised units:")
    w("# POW = HAN = EN = 1 for both sides. The sim's maths only reads build shares and r = player total / opponent total")
    w("# (equations.clash_progress, heat_capacity), so this is exactly 'even split at r = 1' and carries no balance number.")
    w("const PARITY_PLACEHOLDER_UNITS := {\"pow\": 1, \"han\": 1, \"en\": 1}")
    bpin = subprocess.check_output(["git", "-C", str(REPO), "log", "-1", "--format=%h", "--", BLOCKS], text=True).strip()
    btxt = subprocess.check_output(["git", "-C", str(REPO), "show", "%s:%s" % (bpin, BLOCKS)], text=True)
    dj = json.loads(btxt); bl = btxt.splitlines()
    def bline(car):
        for i, l in enumerate(bl, 1):
            if l.strip().startswith('"%s"' % car): return i
    w("# Barry's car stat blocks: %s @ %s (status: %s)" % (BLOCKS, bpin, dj["status"]))
    w("# Rule: %s. Parity cap r %s (%s @ %s:%d)." % (dj["rule"], dj["parity_cap_r"], BLOCKS, bpin, [i for i, l in enumerate(bl, 1) if "parity_cap_r" in l][0]))
    w("# Race settings in that file: %s" % json.dumps(dj["race"]))
    w("# Still marked UNAPPROVED. Used only when race_config.json use_draft_blocks = true. TODO(barry): pending parity block (approval).")
    for car, v in dj["cars"].items():
        w("#   %s: %s:%d @ %s" % (car, BLOCKS, bline(car), bpin))
    w("const CAR_BLOCKS_PIN := %s" % json.dumps(bpin))
    w("const CAR_DRAFT_BLOCKS := %s" % gd({k: {"pow": v["pow"], "han": v["han"], "en": v["en"]} for k, v in dj["cars"].items()}))
    w("const CAR_BLOCK_TUNE := %s" % gd({k: v.get("tune", "") for k, v in dj["cars"].items()}))
    w("static var CAR_BLOCKS_PARITY_CAP_R = %s" % gd(float(dj["parity_cap_r"])))
    (REPO / "scripts" / "globals.gd").write_text("\n".join(out) + "\n")
    print("wrote globals.gd @", pin[:7], "lap", tname, lap)

if __name__ == "__main__":
    main()
